def recommend_spot(mood):
    candidates = LOCATION_DATA[mood]  # 해당 분위기의 10개 장소 리스트 가져오기
    chosen_spot = random.choice(candidates)  # 리스트에서 무작위로 1개 추출
    return chosen_spot


